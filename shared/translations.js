/**
 * Get translation for a key and locale, with optional {param} interpolation.
 * @param {string} key - Translation key
 * @param {string} locale - Locale ('ru', 'en', etc.)
 * @param {Object} [params] - Values for {placeholders} in the string
 * @returns {string} Translated string
 */
export function t(key, locale = "en", params) {
  const currentLocale = TRANSLATIONS[locale] ? locale : "en";
  let str = TRANSLATIONS[currentLocale][key] ?? TRANSLATIONS["en"][key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      str = str.split(`{${name}}`).join(String(value));
    }
  }
  return str;
}
